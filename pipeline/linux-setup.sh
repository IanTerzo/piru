#!/usr/bin/env bash
#
# Set up a Linux machine to work on everything in this repo that does not need
# Xcode: the data pipeline, CI's Python job, and SwiftFormat/SwiftLint.
#
# The iOS app and the Android APK both compile only on macOS (Xcode, and Skip's
# iOS-triple transpile phase). Build them on GitHub's macOS runners with the
# "macOS builds" workflow (.github/workflows/macos-builds.yml) and download the
# artifacts; see "Working on Linux" in CONTRIBUTING.md.
#
# Everything installs outside the checkout, under $PIRU_LINUX
# (default ${XDG_CACHE_HOME:-~/.cache}/piru-linux), at the versions CI pins:
#   venv/   Python 3.13 with ruff, rdkit, pyyaml, pillow
#   bin/    swiftformat, swiftlint (pinned Linux release binaries, hash-checked)
# Nothing is installed with sudo. OpenBabel is the one system package; the
# script tells you to install it when it is missing.
#
# USAGE
#   pipeline/linux-setup.sh            # install / verify, then fetch the DB
#   source "${XDG_CACHE_HOME:-$HOME/.cache}/piru-linux/env.sh"   # every shell
#
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

# Keep these in step with .github/workflows/ci.yml and the table in CLAUDE.md.
PYTHON_VERSION=3.13
RUFF_VERSION=0.15.15
RDKIT_VERSION=2026.3.4
SWIFTFORMAT_VERSION=0.63.0
SWIFTFORMAT_LINUX_SHA256=b4a3cbb8c852a0baaf9adf853e221ff1dabf921a3d8957a602e0bda3af8470f1
SWIFTLINT_VERSION=0.65.1
SWIFTLINT_LINUX_SHA256=caeed6f4a679c35539ffaf124f6c4ab4a8416917f7d8796279dc52b74026059d

PIRU_LINUX="${PIRU_LINUX:-${XDG_CACHE_HOME:-$HOME/.cache}/piru-linux}"
VENV="$PIRU_LINUX/venv"
BIN="$PIRU_LINUX/bin"
mkdir -p "$BIN" "$PIRU_LINUX/downloads"

step() { printf '\n\033[1;36m▸ %s\033[0m\n' "$*"; }
sha256() { python3 -c 'import hashlib,sys; print(hashlib.sha256(open(sys.argv[1],"rb").read()).hexdigest())' "$1"; }

[ "$(uname -s)" = Linux ] || { echo "linux-setup: this is the Linux setup; on macOS follow CONTRIBUTING.md" >&2; exit 1; }
[ "$(uname -m)" = x86_64 ] || echo "linux-setup: warning: the pinned SwiftFormat/SwiftLint binaries are x86_64" >&2

# ── Python 3.13 venv ──────────────────────────────────────────────────────────
step "Python $PYTHON_VERSION venv → $VENV"
if [ ! -x "$VENV/bin/python" ] || ! "$VENV/bin/python" -c "import sys; sys.exit(sys.version_info[:2] != (3, 13))"; then
    rm -rf "$VENV"
    if command -v "python$PYTHON_VERSION" > /dev/null; then
        "python$PYTHON_VERSION" -m venv "$VENV"
    else
        # No system 3.13 (Debian 12 ships 3.11): uv fetches a standalone CPython.
        UV="$(command -v uv || true)"
        if [ -z "$UV" ]; then
            python3 -m venv "$PIRU_LINUX/uv-bootstrap"
            "$PIRU_LINUX/uv-bootstrap/bin/pip" install -q uv
            UV="$PIRU_LINUX/uv-bootstrap/bin/uv"
        fi
        UV_PYTHON_INSTALL_DIR="$PIRU_LINUX/pythons" "$UV" venv --seed --python "$PYTHON_VERSION" "$VENV"
    fi
fi
"$VENV/bin/python" -m pip install -q --upgrade pip
"$VENV/bin/python" -m pip install -q "ruff==$RUFF_VERSION" "rdkit==$RDKIT_VERSION" pyyaml pillow pre-commit
"$VENV/bin/python" --version

# ── SwiftFormat / SwiftLint (Linux release binaries) ─────────────────────────
fetch_checked() { # url file sha
    local out="$PIRU_LINUX/downloads/$2"
    [ -f "$out" ] && [ "$(sha256 "$out")" = "$3" ] && return 0
    curl -fsSL -o "$out" "$1"
    [ "$(sha256 "$out")" = "$3" ] || { echo "linux-setup: checksum mismatch for $1" >&2; rm -f "$out"; exit 1; }
}
step "SwiftFormat $SWIFTFORMAT_VERSION, SwiftLint $SWIFTLINT_VERSION → $BIN"
if [ "$("$BIN/swiftformat" --version 2> /dev/null)" != "$SWIFTFORMAT_VERSION" ]; then
    fetch_checked "https://github.com/nicklockwood/SwiftFormat/releases/download/$SWIFTFORMAT_VERSION/swiftformat_linux.zip" \
        "swiftformat-$SWIFTFORMAT_VERSION.zip" "$SWIFTFORMAT_LINUX_SHA256"
    unzip -qo -d "$PIRU_LINUX/downloads/swiftformat" "$PIRU_LINUX/downloads/swiftformat-$SWIFTFORMAT_VERSION.zip"
    install -m 755 "$PIRU_LINUX/downloads/swiftformat/swiftformat_linux" "$BIN/swiftformat"
fi
if [ "$("$BIN/swiftlint" --version 2> /dev/null)" != "$SWIFTLINT_VERSION" ]; then
    fetch_checked "https://github.com/realm/SwiftLint/releases/download/$SWIFTLINT_VERSION/swiftlint_linux_amd64.zip" \
        "swiftlint-$SWIFTLINT_VERSION.zip" "$SWIFTLINT_LINUX_SHA256"
    unzip -qo -d "$PIRU_LINUX/downloads/swiftlint" "$PIRU_LINUX/downloads/swiftlint-$SWIFTLINT_VERSION.zip"
    # The static build: the dynamic one needs a Swift runtime installed.
    install -m 755 "$PIRU_LINUX/downloads/swiftlint/swiftlint-static" "$BIN/swiftlint"
fi
echo "swiftformat $("$BIN/swiftformat" --version), swiftlint $("$BIN/swiftlint" --version)"

# ── env.sh ───────────────────────────────────────────────────────────────────
cat > "$PIRU_LINUX/env.sh" << EOF
# Generated by pipeline/linux-setup.sh. Source it in each shell.
export PIRU_LINUX="$PIRU_LINUX"
export VIRTUAL_ENV="$VENV"
export PATH="$BIN:$VENV/bin:\$PATH"
EOF

# ── System packages (not installed for you) ──────────────────────────────────
step "System packages"
missing=()
command -v obabel > /dev/null || missing+=(openbabel)
command -v unzip > /dev/null || missing+=(unzip)
command -v sqlite3 > /dev/null || missing+=(sqlite3)
if [ ${#missing[@]} -gt 0 ]; then
    echo "missing (CI installs these with apt; the identifier checks need obabel):"
    echo "    sudo apt-get install -y ${missing[*]}"
else
    echo "ok"
fi

# ── The bundled substance DB ─────────────────────────────────────────────────
step "Substance DB"
pipeline/fetch-db.sh

cat << EOF

ready. In each shell:
    source "$PIRU_LINUX/env.sh"

then:
    python3 pipeline/ci_local.py        # CI's Python job (--all adds the ~200 s obabel check)
    swiftformat --lint . && swiftlint lint --quiet
    pipeline/build.sh fast              # rebuild the substance DB
    pre-commit install --hook-type pre-commit --hook-type pre-push
EOF
